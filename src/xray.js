  _renderJSONFlat(val, jpath = "card", depth = 0, inline = false) {
    if (val === null) return `<span class="jb">null</span>`;
    if (typeof val === "boolean") return `<span class="jb">${val}</span>`;
    if (typeof val === "number") return `<span class="jn">${val}</span>`;
    if (typeof val === "string") {
      const clean = val.length > 260 ? val.slice(0, 260) + "..." : val;
      return `<span class="js">"${escHtml(clean)}"</span>`;
    }

    const isArr = Array.isArray(val);
    const entries = isArr ? val.map((v, idx) => [null, v, idx]) : Object.entries(val).map(([k, v]) => [k, v, k]);
    const open = isArr ? "[" : "{";
    const close = isArr ? "]" : "}";
    if (!entries.length) return `${open}${close}`;

    if (inline) {
      const parts = entries.map(([k, v, seg]) => {
        const childPath = isArr ? `${jpath}[${seg}]` : `${jpath}.${seg}`;
        const isSel = k !== null && (this.selectedFieldPath ? this.selectedFieldPath === childPath : false);
        const kHtml = k !== null
          ? `<span class="jk${isSel ? " sel" : ""}" data-field="${escHtml(k)}" data-jpath="${escHtml(childPath)}">"${escHtml(k)}"</span>: `
          : "";
        return `${kHtml}${this._renderJSONFlat(v, childPath, depth + 1, true)}`;
      });
      return `${open} ${parts.join(", ")} ${close}`;
    }

    const indent = "  ".repeat(depth);
    const childIndent = "  ".repeat(depth + 1);
    const inner = entries.map(([k, v, seg], i) => {
      const comma = i < entries.length - 1 ? "," : "";
      const childPath = isArr ? `${jpath}[${seg}]` : `${jpath}.${seg}`;
      const isSel = k !== null && (this.selectedFieldPath ? this.selectedFieldPath === childPath : false);
      const kHtml = k !== null
        ? `<span class="jk${isSel ? " sel" : ""}" data-field="${escHtml(k)}" data-jpath="${escHtml(childPath)}">"${escHtml(k)}"</span>: `
        : "";
      const vRendered = this._renderJSONFlat(v, childPath, depth + 1, false);
      return `${childIndent}${kHtml}${vRendered}${comma}`;
    }).join("\n");
    return `${open}\n${inner}\n${indent}${close}`;
  },

  _renderJSONVal(val, depth, focusKey, keyName, jpath = "root") {
    if (val === null) return `<span class="jb">null</span>`;
    if (typeof val === "boolean") return `<span class="jb">${val}</span>`;
    if (typeof val === "number") return `<span class="jn">${val}</span>`;
    if (typeof val === "string") {
      const clean = val.length > 260 ? val.slice(0, 260) + "..." : val;
      return `<span class="js">"${escHtml(clean)}"</span>`;
    }

    const isArr = Array.isArray(val);
    const entries = isArr ? val.map((v, idx) => [null, v, idx]) : Object.entries(val).map(([k, v]) => [k, v, k]);
    const open = isArr ? "[" : "{";
    const close = isArr ? "]" : "}";
    if (!entries.length) return `${open}${close}`;

    const canFold = depth <= 1;
    const isFocus = keyName && focusKey && keyName === focusKey;
    const defaultFolded = canFold && !isFocus && keyName === "tools" && depth === 1 && entries.length > 2;
    const folded = canFold && (this._foldOverrides.has(jpath) ? this._foldOverrides.get(jpath) : defaultFolded);
    const indent = "  ".repeat(depth);
    const childIndent = "  ".repeat(depth + 1);

    const inner = entries.map(([k, v, seg], i) => {
      const comma = i < entries.length - 1 ? "," : "";
      const kIsFocus = k && focusKey && k === focusKey;
      const childPath = isArr ? `${jpath}[${seg}]` : `${jpath}.${seg}`;
      const isSelected = k !== null && (this.selectedFieldPath ? this.selectedFieldPath === childPath : this.selectedField === k);
      const kHtml = k !== null
        ? `<span class="jk${isSelected ? " sel" : ""}" data-field="${escHtml(k)}" data-jpath="${escHtml(childPath)}">"${escHtml(k)}"</span>: `
        : "";
      const vRendered = this._renderJSONVal(v, depth + 1, focusKey, k, childPath);
      const line = `${childIndent}${kHtml}${vRendered}${comma}`;
      return kIsFocus ? `__BLOCK_START__<span class="jfocus-row json-focus-ring">${line}</span>__BLOCK_END__` : line;
    }).join("\n")
      .replace(/\n?__BLOCK_START__/g, "")
      .replace(/__BLOCK_END__\n?/g, "");

    if (!canFold) {
      return `${open}\n${inner}\n${indent}${close}`;
    }

    const summary = isArr ? ` ... ${entries.length} items ` : ` ... ${entries.length} keys `;
    return `<span class="jnode${folded ? " folded" : ""}" data-jpath="${escHtml(jpath)}"><span class="jfold">${folded ? "▸" : "▾"}</span>${open}<span class="jellipsis">${summary}</span><span class="jbody">\n${inner}\n${indent}</span>${close}</span>`;
  },

